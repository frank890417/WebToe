#!/usr/bin/env node
// render-og — the social card, site/assets/og.png (1200×630).
//
//   node tools/site/render-og.mjs      (npm run site:og)
//
// Writes the card's source, tools/site/og-card.html (the drawing is example 03's
// real network, generated like the homepage's), then screenshots it with
// headless Chrome through playwright-core. Both files are committed.

import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { chromium } from 'playwright-core';
import { ROOT } from './build.mjs';
import { networkSvg } from './network-svg.mjs';

const lfo = JSON.parse(fs.readFileSync(path.join(ROOT, 'apps/web/public/examples/03-lfo-garden.webtoe.json'), 'utf8'));
const net = networkSvg(lfo, { id: 'og-net', label: 'Example 03, lfo garden', flow: false });

const html = `<!DOCTYPE html>
<!-- Source of site/assets/og.png (1200×630). Generated by tools/site/render-og.mjs; edit that, not this. -->
<html lang="en">
<head>
<meta charset="utf-8">
<title>og card</title>
<link rel="stylesheet" href="../../site/assets/site.css">
<style>
  html, body { margin: 0; width: 1200px; height: 630px; overflow: hidden; background: var(--ink); }
  .card { position: relative; width: 1200px; height: 630px; }
  .fig { position: absolute; left: 610px; top: 0; right: 0; bottom: 0; background: var(--dots); border-left: 1px solid var(--line); }
  .fig .net { position: absolute; left: 26px; right: 22px; top: 126px; width: auto; }
  .fig .net .nm { font-size: 15px; }
  .fig .net .ty { font-size: 11px; }
  .txt { position: absolute; left: 64px; top: 72px; width: 510px; }
  .wm { font: 800 124px/.84 var(--sans); font-stretch: 112%; letter-spacing: -.05em; color: var(--fg); margin: 0 0 0 -6px; }
  .sub { font: 500 34px/1.16 var(--sans); color: var(--fg); margin: 28px 0 0; }
  .fams { display: flex; gap: 14px; margin: 30px 0 0; font: 500 15px var(--mono); letter-spacing: .06em; }
  .fams span { border-top: 3px solid var(--c); padding-top: 6px; color: var(--c); }
  .foot { position: absolute; left: 64px; bottom: 50px; display: flex; gap: 20px; align-items: center;
    font: 500 14px var(--mono); color: var(--fg-3); letter-spacing: .06em; text-transform: uppercase; }
  .foot i { width: 10px; height: 10px; border-radius: 50%; background: var(--sig); box-shadow: 0 0 0 4px var(--sig-dim); }
  .foot span:first-of-type { color: var(--fg); }
  .tag { position: absolute; right: 26px; bottom: 50px; font: 500 14px var(--mono); color: var(--fg-3); letter-spacing: .04em; }
</style>
</head>
<body>
<div class="card">
  <div class="fig">${net}<p class="tag">03 · lfo garden — a real WebToe network</p></div>
  <div class="txt">
    <p class="wm">WebToe</p>
    <p class="sub">A web-native dataflow engine for real-time visuals.</p>
    <p class="fams"><span style="--c:var(--top)">TOP</span><span style="--c:var(--chop)">CHOP</span><span style="--c:var(--sop)">SOP</span><span style="--c:var(--mat)">MAT</span><span style="--c:var(--comp)">COMP</span><span style="--c:var(--dat)">DAT</span></p>
  </div>
  <div class="foot"><i></i><span>webtoe.openaudiovisual.com</span><span>MIT · open source</span></div>
</div>
</body>
</html>
`;

const src = path.join(ROOT, 'tools/site/og-card.html');
fs.writeFileSync(src, html);

const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--allow-file-access-from-files'] });
const page = await browser.newPage({ viewport: { width: 1200, height: 630 }, deviceScaleFactor: 1 });
await page.goto(pathToFileURL(src).href);
await page.evaluate(() => document.fonts.ready);
await page.waitForTimeout(200);
const out = path.join(ROOT, 'site/assets/og.png');
await page.screenshot({ path: out, clip: { x: 0, y: 0, width: 1200, height: 630 } });
await browser.close();
console.log(`wrote site/assets/og.png (${(fs.statSync(out).size / 1024).toFixed(0)} KB) from tools/site/og-card.html`);
